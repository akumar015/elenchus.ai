"use client";

import { useState } from "react";
import { ThoughtCard } from "@/types/spar";
import { Brain, Target, AlertTriangle, Zap, Copy, Download, Check } from "lucide-react";

interface AtomicThoughtCardProps {
  card: ThoughtCard;
  topicTitle?: string;
  // Optional metadata for richer exports
  totalTurns?: number;
  finalStage?: string;
  language?: string;
}

const SECTIONS = [
  {
    key: "core_thesis" as const,
    label: "Core Thesis",
    icon: Brain,
    borderColor: "border-elenchus-border",
    bgColor: "bg-elenchus-surface-2/60",
    iconColor: "text-elenchus-stone",
  },
  {
    key: "user_stance" as const,
    label: "Your Stance",
    icon: Target,
    borderColor: "border-elenchus-emerald/30",
    bgColor: "bg-elenchus-emerald/5",
    iconColor: "text-emerald-400",
  },
  {
    key: "blind_spots" as const,
    label: "Blind Spots Exposed",
    icon: AlertTriangle,
    borderColor: "border-elenchus-amber/30",
    bgColor: "bg-elenchus-amber/5",
    iconColor: "text-elenchus-amber",
  },
  {
    key: "key_insight" as const,
    label: "Key Insight",
    icon: Zap,
    borderColor: "border-elenchus-terracotta/30",
    bgColor: "bg-elenchus-terracotta/5",
    iconColor: "text-elenchus-terracotta",
  },
] as const;

// ---------------------------------------------------------------------------
// Export helpers
// ---------------------------------------------------------------------------

function buildMarkdown(
  card: ThoughtCard,
  topicTitle?: string,
  totalTurns?: number,
  finalStage?: string,
  language?: string,
): string {
  const date = new Date().toLocaleDateString("en-IN", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
  const langLabel = language === "hi-IN" ? "Hinglish" : "English";
  const meta = [
    totalTurns !== undefined ? `${totalTurns} turns` : null,
    finalStage ? `${finalStage} stage` : null,
    langLabel,
    date,
  ]
    .filter(Boolean)
    .join(" · ");

  return [
    topicTitle ? `# Atomic Thought Card: ${topicTitle}` : "# Atomic Thought Card",
    "> Generated by **elenchus.ai** — The Socratic Conversational Sparring Engine",
    "",
    "## Core Thesis",
    card.core_thesis,
    "",
    "## Your Stance",
    card.user_stance,
    "",
    "## Blind Spots Exposed",
    card.blind_spots,
    "",
    "## Key Insight",
    card.key_insight,
    "",
    "---",
    `*${meta}*`,
  ].join("\n");
}

function buildJSON(
  card: ThoughtCard,
  topicTitle?: string,
  totalTurns?: number,
  finalStage?: string,
  language?: string,
): string {
  return JSON.stringify(
    {
      source: "elenchus.ai",
      generated_at: new Date().toISOString(),
      topic: topicTitle ?? null,
      total_turns: totalTurns ?? null,
      final_stage: finalStage ?? null,
      language: language ?? null,
      thought_card: card,
    },
    null,
    2,
  );
}

function triggerDownload(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

// ---------------------------------------------------------------------------
// Component
// ---------------------------------------------------------------------------

export function AtomicThoughtCard({
  card,
  topicTitle,
  totalTurns,
  finalStage,
  language,
}: AtomicThoughtCardProps) {
  const [copied, setCopied] = useState(false);

  const handleCopyMarkdown = async () => {
    const md = buildMarkdown(card, topicTitle, totalTurns, finalStage, language);
    await navigator.clipboard.writeText(md);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadJSON = () => {
    const json = buildJSON(card, topicTitle, totalTurns, finalStage, language);
    const slug = topicTitle
      ? topicTitle.toLowerCase().replace(/\s+/g, "-").slice(0, 40)
      : "thought-card";
    triggerDownload(json, `elenchus-${slug}.json`, "application/json");
  };

  return (
    <div className="space-y-4">
      {/* Header */}
      <div className="space-y-1">
        <p className="font-mono text-[10px] uppercase tracking-widest text-elenchus-emerald">
          Atomic Thought Card
        </p>
        {topicTitle && (
          <p className="font-serif text-sm text-elenchus-stone italic">
            &ldquo;{topicTitle}&rdquo;
          </p>
        )}
      </div>

      {/* Four content sections */}
      <div className="space-y-3">
        {SECTIONS.map(({ key, label, icon: Icon, borderColor, bgColor, iconColor }) => (
          <div
            key={key}
            className={`rounded-lg border ${borderColor} ${bgColor} p-3.5 space-y-1.5`}
          >
            <div className="flex items-center gap-2">
              <Icon className={`w-3.5 h-3.5 ${iconColor} flex-shrink-0`} />
              <span className="font-mono text-[10px] uppercase tracking-wider text-elenchus-stone">
                {label}
              </span>
            </div>
            <p className="text-xs text-elenchus-chalk leading-relaxed pl-5">
              {card[key]}
            </p>
          </div>
        ))}
      </div>

      {/* Export Actions */}
      <div className="flex items-center gap-2 pt-1 border-t border-elenchus-border">
        <span className="font-mono text-[10px] uppercase tracking-wider text-elenchus-muted mr-auto">
          Export
        </span>

        {/* Copy as Markdown */}
        <button
          onClick={handleCopyMarkdown}
          title="Copy as Markdown (Notion / Obsidian)"
          className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-md border border-elenchus-border bg-elenchus-surface-2 font-mono text-[10px] uppercase tracking-wider text-elenchus-stone hover:text-elenchus-chalk hover:border-elenchus-emerald/50 transition-all"
        >
          {copied ? (
            <>
              <Check className="w-3 h-3 text-emerald-400" />
              <span className="text-emerald-400">Copied!</span>
            </>
          ) : (
            <>
              <Copy className="w-3 h-3" />
              <span>Copy MD</span>
            </>
          )}
        </button>

        {/* Download JSON */}
        <button
          onClick={handleDownloadJSON}
          title="Download as JSON"
          className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-md border border-elenchus-border bg-elenchus-surface-2 font-mono text-[10px] uppercase tracking-wider text-elenchus-stone hover:text-elenchus-chalk hover:border-elenchus-terracotta/50 transition-all"
        >
          <Download className="w-3 h-3" />
          <span>JSON</span>
        </button>
      </div>
    </div>
  );
}